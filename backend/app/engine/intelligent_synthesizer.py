def _try_solve_cs_theory(prompt: str) -> Optional[str]:
    """Recognizes computer science and AI architecture concepts."""
    p = prompt.lower()

    if "transformer" in p or "attention" in p:
        return (
            "### Transformer Architecture & Self-Attention\n\n"
            "The Transformer architecture replaces recurrence with **Scaled Dot-Product Self-Attention**:\n\n"
            "$$\\text{Attention}(Q, K, V) = \\text{softmax}\\left(\\frac{QK^T}{\\sqrt{d_k}}\\right)V$$\n\n"
            "**Core Components**:\n"
            "1. **Multi-Head Attention (MHA)**: Projects queries, keys, and values into multiple subspaces ($h$ heads) allowing the model to jointly attend to information from different representation subspaces.\n"
            "2. **Positional Encoding**: Sinusoidal or RoPE (Rotary Position Embeddings) inject sequential order into parallel token computations.\n"
            "3. **Feed-Forward Networks (FFN)**: Two linear transformations with activation (e.g. SwiGLU or GeLU) applied identically to each position.\n"
            "4. **Residual Connections & LayerNorm / RMSNorm**: Stabilize gradient propagation across deep networks."
        )

    if "cap theorem" in p:
        return (
            "### The CAP Theorem (Brewer's Theorem)\n\n"
            "The CAP theorem states that any distributed data store can simultaneously provide at most **two out of the three** guarantees:\n\n"
            "1. **Consistency (C)**: Every read receives the most recent write or an error.\n"
            "2. **Availability (A)**: Every non-failing node returns a non-error response for every request (without guarantee of containing the latest write).\n"
            "3. **Partition Tolerance (P)**: The system continues to operate despite an arbitrary number of messages being dropped or delayed by the network.\n\n"
            "> In distributed networks, network partitions (**P**) are inevitable. Therefore, systems must choose between **CP** (e.g., ZooKeeper, HBase, etcd) and **AP** (e.g., DynamoDB, Cassandra, CouchDB)."
        )

    if "dijkstra" in p:
        return (
            "### Dijkstra's Shortest Path Algorithm\n\n"
            "Dijkstra's algorithm finds the shortest path from a single source vertex to all other vertices in a weighted graph with **non-negative edge weights**.\n\n"
            "**Algorithm**:\n"
            "1. Initialize distances: $dist[source] = 0$, all other vertices $dist[v] = \\infty$.\n"
            "2. Insert $(0, source)$ into a min-priority queue (min-heap).\n"
            "3. While the queue is not empty, pop vertex $u$ with minimum distance.\n"
            "4. For each neighbor $v$ with edge weight $w(u, v)$:\n"
            "   $$\\text{if } dist[u] + w(u, v) < dist[v]: dist[v] = dist[u] + w(u, v)$$\n"
            "   Push $(dist[v], v)$ into the priority queue.\n\n"
            "**Complexity**:\n"
            "- **Time**: $O((V + E) \\log V)$ using a binary min-heap.\n"
            "- **Space**: $O(V)$ for distance and visited arrays."
        )

    if "overfitting" in p:
        return (
            "### Overfitting in Machine Learning\n\n"
            "**Overfitting** occurs when a statistical or machine learning model learns the training data's noise and random fluctuations rather than the underlying general distribution, leading to low training error but high test error.\n\n"
            "**Common Mitigation Techniques**:\n"
            "- **Regularization**: $L_1$ (Lasso for sparsity) and $L_2$ (Ridge / Weight Decay to constrain parameter magnitudes).\n"
            "- **Cross-Validation**: $k$-fold cross-validation to rigorously validate generalization performance.\n"
            "- **Early Stopping**: Halting training when validation loss stops improving.\n"
            "- **Dropout**: Randomly deactivating neurons during training to prevent co-adaptation.\n"
            "- **Data Augmentation**: Expanding training dataset volume with synthetic perturbations."
        )

    if "backpropagation" in p:
        return (
            "### Backpropagation Algorithm\n\n"
            "**Backpropagation** computes the gradient of the loss function $\\mathcal{L}$ with respect to all learnable weights $W$ in a neural network via the recursive application of the calculus **Chain Rule**:\n\n"
            "$$\\frac{\\partial \\mathcal{L}}{\\partial W_{ij}^{(l)}} = \\frac{\\partial \\mathcal{L}}{\\partial z_j^{(l)}} \\cdot \\frac{\\partial z_j^{(l)}}{\\partial W_{ij}^{(l)}} = \\delta_j^{(l)} \\cdot a_i^{(l-1)}$$\n\n"
            "**Key Steps**:\n"
            "1. **Forward Pass**: Compute activations layer by layer up to the loss $\\mathcal{L}$.\n"
            "2. **Backward Pass**: Compute output error $\\delta^{(L)} = \\nabla_a \\mathcal{L} \\odot \\sigma'(z^{(L)})$.\n"
            "3. **Error Propagation**: Propagate $\\delta^{(l)}$ backwards through transposed weight matrices.\n"
            "4. **Parameter Update**: Update weights via gradient descent: $W \\leftarrow W - \\eta \\nabla_W \\mathcal{L}$."
        )

    return None


