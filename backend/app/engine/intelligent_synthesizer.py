def _try_solve_math(prompt: str) -> Optional[str]:
    """Dynamically parses and evaluates basic arithmetic and mathematical expressions."""
    p = prompt.lower().strip()
    # Match patterns like: calculate 15 * 4, what is 2^8, solve 100 / 5, 25 + 75
    math_match = re.search(r'(?:calculate|what is|evaluate|solve|compute)?\s*([0-9\.\s\+\-\*\/\^\(\)]+)(?:\?|$)', p)
    if not math_match:
        return None
    expr_str = math_match.group(1).strip()
    if not any(c in expr_str for c in "+-*/^"):
        return None
    # Check if there are actual digits
    if not re.search(r'\d', expr_str):
        return None

    # Replace ^ with ** for python eval
    clean_expr = expr_str.replace("^", "**")
    # Only allow safe mathematical characters
    if not re.match(r'^[0-9\.\s\+\-\*\/\(\)\%]+$', clean_expr):
        return None

    try:
        # Safe eval with restricted globals
        result = eval(clean_expr, {"__builtins__": None, "math": math}, {})
        return (
            f"### Mathematical Evaluation\n\n"
            f"**Expression**: `{expr_str}`\n\n"
            f"**Step-by-step Solution**:\n"
            f"1. Parsing arithmetic operators under standard operator precedence (PEMDAS).\n"
            f"2. Evaluated expression: `{clean_expr}`\n\n"
            f"**Result**: **`{result}`**"
        )
    except Exception:
        return None


